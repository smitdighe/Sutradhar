pytestmark = pytest.mark.contract

CONTRACT = Path(__file__).resolve().parents[2] / "docs" / "API_CONTRACT.md"

# Endpoints are declared as level-four headings holding a method and a path in
# backticks, e.g. "#### `POST {API_PREFIX}/items`".
_HEADING = re.compile(r"^#### `([A-Z]+) (\S+)`\s*$", re.M)

# Words that mean the document was left unfinished, plus one that names a thing
# this project does not have. Case-insensitive.
_FORBIDDEN = ("tbd", "todo", "probably", "should be", "github")


def contract_text() -> str:
    return CONTRACT.read_text(encoding="utf-8")


def documented_operations() -> set[str]:
    """``{"get /api/v1/items", ...}`` — the document's endpoint set, resolved.

    ``{API_PREFIX}`` in the document is substituted with the configured prefix so
    the comparison is against real paths rather than against a placeholder.
    """
    prefix = get_settings().api_prefix
    return {
        f"{method.lower()} {path.replace('{API_PREFIX}', prefix)}"
        for method, path in _HEADING.findall(contract_text())
    }


def _section(heading: str, until: str) -> str:
    """The document text between two headings. Both must be present."""
    text = contract_text()
    assert heading in text, f"{heading} is missing from docs/API_CONTRACT.md"
    body = text.split(heading, 1)[1]
    return body.split(until, 1)[0] if until in body else body


def _codes_in_error_tables() -> set[str]:
    """Codes tabulated in section 4 and section 4.1, from the leading cell.

    A row there begins ``| `CODE` |``. Nothing else in the document has that
    shape, so this cannot pick up prose.
    """
    return set(
        re.findall(r"^\| `([A-Z][A-Z0-9_]+)`", _section("## 4. Error codes", "## 5."), re.M)
    )


# The status each exception class answers with when the raise site does not say.
_DEFAULT_STATUS = {
    "AppError": 500,
    "AuthError": 401,
    "ChainUnavailable": 503,
    "ConflictError": 409,
    "ForbiddenError": 403,
    "InsufficientStorageError": 507,
    "NotFoundError": 404,
    "RateLimitError": 429,
    "UnavailableError": 503,
    "ValidationError": 422,
}

APP_DIR = Path(__file__).resolve().parents[2] / "app"


def statuses_raised_in_source() -> dict[str, set[int]]:
    """``{"MEDIA_TOO_LARGE": {413}, ...}`` read out of ``app/``.

    A static read, and deliberately a partial one: a code raised through a
    helper that takes the code as an argument -- ``app.catalog.validator._reject``
    is the one that does -- is invisible here. So this is only ever used to
    contradict the document, never to demand that a code appear. A code this
    cannot resolve is simply not checked.
    """
    found: dict[str, set[int]] = collections.defaultdict(set)
    for path in APP_DIR.rglob("*.py"):
        if path.as_posix().endswith("core/errors.py"):
            continue
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if not isinstance(node, ast.Call):
                continue
            function = node.func
            name = (
                function.id
                if isinstance(function, ast.Name)
                else getattr(function, "attr", None)
            )
            if name not in _DEFAULT_STATUS:
                continue
            code = status = None
            for keyword in node.keywords:
                if keyword.arg == "code" and isinstance(keyword.value, ast.Attribute):
                    code = keyword.value.attr
                if keyword.arg == "status" and isinstance(keyword.value, ast.Constant):
                    status = keyword.value.value
            if code is not None:
                found[code].add(status or _DEFAULT_STATUS[name])
    return dict(found)


def documented_statuses() -> dict[str, set[int]]:
    """Every ``| `CODE` | <status> |`` row in the document, by code."""
    rows = re.findall(
        r"^\| `([A-Z][A-Z0-9_]+)` \| (\d{3})",
        contract_text(),
        re.M,
    )
    found: dict[str, set[int]] = collections.defaultdict(set)
    for code, status in rows:
        found[code].add(int(status))
    return dict(found)


def served_operations() -> set[str]:
    from app.main import create_app

    schema = create_app().openapi()
    return {
        f"{method.lower()} {path}"
        for path, operations in schema["paths"].items()
        for method in operations
    }


class TestTheDocumentExists:
    def test_the_contract_is_present(self) -> None:
        assert CONTRACT.is_file(), f"{CONTRACT} does not exist"

    def test_the_heading_pattern_actually_matches_something(self) -> None:
        """Guards against the whole suite passing on a regex that matches nothing.

        Every assertion below compares two sets. A parser that silently returns
        an empty set would make the set-difference checks trivially pass in one
        direction and blame the application in the other, which is exactly the
        failure mode the route-inventory bug had in Phase 12.
        """
        assert len(documented_operations()) >= 40


class TestEndpointSets:
    def test_the_document_and_the_application_serve_the_same_endpoints(self) -> None:
        documented = documented_operations()
        served = served_operations()

        undocumented = sorted(served - documented)
        phantom = sorted(documented - served)

        assert not undocumented, (
            "these endpoints are served by the application and are absent from "
            f"docs/API_CONTRACT.md: {undocumented}. A frontend reading the "
            "contract would never know they exist."
        )
        assert not phantom, (
            "these endpoints are documented in docs/API_CONTRACT.md and are not "
            f"served by the application: {phantom}. A frontend would call them "
            "and get a 404."
        )

    def test_the_operation_count_in_the_prose_is_right(self) -> None:
        """Section 3 opens by naming a number. Numbers in prose go stale."""
        stated = re.search(r"^(\d+) operations\.", contract_text(), re.M)
        assert stated is not None, "section 3 no longer states an operation count"
        assert int(stated.group(1)) == len(served_operations())

    def test_no_endpoint_is_documented_twice(self) -> None:
        headings = _HEADING.findall(contract_text())
        seen: set[tuple[str, str]] = set()
        duplicates = sorted(
            f"{method} {path}"
            for method, path in headings
            if (method, path) in seen or seen.add((method, path))  # type: ignore[func-returns-value]
        )
        assert not duplicates, f"documented more than once: {duplicates}"


class TestErrorCodes:
    def test_every_code_named_in_the_document_exists_in_the_enum(self) -> None:
        """A documented code the application cannot emit is a dead branch.

        Read from the leading cell of a section-4 table row rather than from
        every backticked capital in the file. Prose in this document legitimately
        names environment variables, a sample tag code, and the six codes that
        were deleted in this phase; a heuristic loose enough to catch a wrong
        error code is loose enough to catch all of those, and a check that fires
        on prose is a check somebody switches off.
        """
        known = {member.name for member in ErrorCode}
        invented = sorted(_codes_in_error_tables() - known)
        assert not invented, (
            "docs/API_CONTRACT.md tabulates these as error codes and "
            f"app/core/errors.py has no such member: {invented}"
        )

    def test_the_error_table_is_not_empty(self) -> None:
        """The check above compares two sets; one of them must be real."""
        assert len(_codes_in_error_tables()) >= 40

    def test_no_documented_status_contradicts_the_raise_site(self) -> None:
        """Catches the class of error a reader cannot catch by reading.

        A wrong status in a frozen contract is a frontend that branches on the
        wrong number, and nothing about the document itself looks wrong. Two of
        these were found by hand while writing it -- ``MEDIA_TOO_LARGE`` is 413
        and ``CATEGORY_RETIRED`` is 422, and both had been written down from the
        shape of the error rather than from the raise site.
        """
        in_source = statuses_raised_in_source()
        wrong: list[str] = []
        for code, documented in sorted(documented_statuses().items()):
            actual = in_source.get(code)
            if actual is None:
                continue
            unexplained = documented - actual
            if unexplained:
                wrong.append(
                    f"{code}: documented as {sorted(unexplained)}, "
                    f"raised in app/ as {sorted(actual)}"
                )
        assert not wrong, (
            "docs/API_CONTRACT.md disagrees with the raise sites:\n" + "\n".join(wrong)
        )

    def test_the_status_scan_resolves_most_codes(self) -> None:
        """The check above is only meaningful while the scan sees real codes."""
        assert len(statuses_raised_in_source()) >= 40

    def test_every_code_in_the_enum_appears_in_the_document(self) -> None:
        text = contract_text()
        missing = sorted(
            member.name for member in ErrorCode if f"`{member.name}`" not in text
        )
        assert not missing, (
            "these error codes exist in app/core/errors.py and are absent from "
            f"docs/API_CONTRACT.md: {missing}. Either document them, or delete "
            "them if nothing raises them."
        )

    def test_every_code_appears_in_the_reachability_table(self) -> None:
        """Section 4.1 maps each code to a test that triggers it.

        A code documented with no reachable trigger is either dead or untested,
        and the table is where that gets decided rather than forgotten.
        """
        text = contract_text()
        table = text.split("### 4.1 Reachability", 1)
        assert len(table) == 2, "section 4.1 is missing from docs/API_CONTRACT.md"

        reachability = table[1]
        missing = sorted(
            member.name for member in ErrorCode if f"`{member.name}`" not in reachability
        )
        assert not missing, (
            "these error codes are documented but do not appear in the "
            f"reachability table in section 4.1: {missing}"
        )


