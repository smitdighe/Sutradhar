"""``docs/API_CONTRACT.md`` is checked against the application, not trusted.

The document is the only thing a separate frontend build has. Nobody who reads
it can ask a follow-up question, so every drift between it and the code becomes
a frontend bug that surfaces at integration time. These tests are what stop that:
the endpoint set, the error-code set and the enum members are all compared
against the running application rather than against anybody's memory.

**The route inventory comes from ``application.openapi()``, deliberately.**
Phase 12 found that a naive walk over ``app.routes`` returns *nothing* under
FastAPI 0.141 — each ``include_router`` call is wrapped in an ``_IncludedRouter``
that keeps the original router and exposes no ``routes`` attribute of its own --
and a route audit built on it passed by finding no routes at all. The OpenAPI
document is generated by FastAPI from the same routers and cannot be empty
without the application being empty, so it is the authority here.
``tests/integration/test_security_sweep.py`` keeps a hand-written walk and
asserts it agrees with this same document, which is where that bug would surface
again.
"""

from __future__ import annotations

import ast
import collections
